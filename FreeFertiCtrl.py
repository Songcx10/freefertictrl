class FreeFertiCtrl:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface

        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)

        # initialize locale
        locale = QSettings().value('locale/userLocale')[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            'FreeFertiCtrl_{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&FreeFertiCtrl')
        # TODO: We are going to let the user set this up in a future iteration
        self.toolbar = self.iface.addToolBar(u'FreeFertiCtrl')
        self.toolbar.setObjectName(u'FreeFertiCtrl')

        #print "** INITIALIZING FreeFertiCtrl"
        self.Export = None
        self.gui_number = 0
        self.map_file_path = None  # 存储处方图路径
        self.plot_file_path = None  # 存储目标地块路径
        self.path_filepath = None  # 存储农机路径规划的路径
        self.xml_file = None  # 存储导出文件的名称
        self.Probar_num = 0
        self.task_name = None  # 存储该任务的名称
        self.file_name = None
        self.pluginIsActive = False
        self.dockwidget = None


    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('FreeFertiCtrl', message)


    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            self.toolbar.addAction(action)

        if add_to_menu:
            self.iface.addPluginToMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

        # 消息提示功能
    def mes_show(self, str, time, mode="info"):
        if mode == "info":
            iface.messageBar().pushMessage(str, level=Qgis.Info, duration=time)
        else:  # mode == "error"
            iface.messageBar().pushMessage(str, level=Qgis.Critical, duration=time)

    # 获取地块原图
    def get_map_raster(self):
        if self.dockwidget.inputLayer_2.isEnabled():
            map_layer = self.dockwidget.inputLayer_2.currentLayer()
        if map_layer is not None:
                # 获取当前输入图层的路径
            file_path = map_layer.source().split("|")[0]
            return file_path

    # 获取目标地块多边形路径
    def get_path_raster(self):
        if self.dockwidget.pathLayer_2.isEnabled():
            path_layer = self.dockwidget.pathLayer_2.currentLayer()
        if path_layer is not None:
                # 获取当前输入图层的路径
            file_path = path_layer.source().split("|")[0]
            return file_path

    # 获取NDVI图像路径
    def get_ndvi_raster(self):
        if self.dockwidget.NDVILayer_2.isEnabled():
            path_layer = self.dockwidget.NDVILayer_2.currentLayer()
        if path_layer is not None:
                # 获取当前输入图层的路径
            file_path = path_layer.source().split("|")[0]
            return file_path

    # 获取生成的长势分析结果图所在路径
    def get_grade_raster(self):
        if self.dockwidget.gradeLayer_2.isEnabled():
            grade_layer = self.dockwidget.gradeLayer_2.currentLayer()
        if grade_layer is not None:
            # 获取当前输入图层的路径
            file_path = grade_layer.source().split("|")[0]
            return file_path

    def update_progress(self, value):
        """更新进度条的回调函数"""
        self.dockwidget.Probar.setValue(value)

            # checkbox状态改变函数

    def on_checkbox_state_changed(self):
        """当 checkbox 状态改变时，启用或禁用 layer_combo_box"""
        if self.dockwidget.IfSelect.isChecked():
                # 如果选中，启用 layer_combo_box
            self.dockwidget.pathLayer_2.setEnabled(True)
        else:
             # 未选中，禁用 layer_combo_box 并清空内容
            self.dockwidget.pathLayer_2.setEnabled(False)
            self.dockwidget.pathLayer_2.setLayer(None)

    # 保存为xml格式的文件，导出按钮的功能
    def save_to_iso_xml(self):
        self.kind = 4
        self.app_data = [self.dockwidget.excellent_2.text(), self.dockwidget.good_2.text(),
                             self.dockwidget.fair_2.text(), self.dockwidget.poor_2.text()]
            # 获取生成的长势分析结果图路径
        self.grade_shp = self.get_grade_raster()
            # 直接将输出文件定义为与该图层名称相同
        self.xml_file = self.grade_shp.replace("_grade.shp", ".xml")
            # bin文件输出与xml文件输出位置相同
        self.ndvi_path = self.get_ndvi_raster()
        self.bin_file = self.ndvi_path.replace(".tif", ".BIN")
        result = com.create_xml(self.grade_shp, self.xml_file, self.bin_file, self.kind, self.app_data,
                                    progress_callback=self.update_progress)
            # 进度条进度
        if result:
            self.dockwidget.Success.setText("Export Success！")
        else:
            self.dockwidget.Success.setText("Export Failed！")

    def get_shp(self):
        try:
                # 获取NDVI栅格路径
            self.ndvi_path = self.get_ndvi_raster()
            if not self.ndvi_path:
                raise ValueError("NDVI raster path is invalid.")

            # 获取目标网格长度，检查是否为有效整数
            self.pixel = self.dockwidget.Pixel_2.text()
            try:
                pixel_size = int(self.pixel)
            except ValueError:
                self.mes_show("Pixel size must be a valid integer.", 5)
                return

            # 判断选择框是否被勾选：如果勾选，使用自定义多边形，否则使用整个地块
            if self.dockwidget.IfSelect.isChecked():
                self.path_filepath = self.get_path_raster()
                if not self.path_filepath:
                    raise ValueError("Path raster is invalid.")
                self.shp_grade_path = self.path_filepath.replace(".shp", "_grade.shp")
                # com.get_ndvi_grade(self.ndvi_path, self.path_filepath, self.shp_grade_path, pixel_size)
                com.ndvi_grid_to_shp2(self.ndvi_path, self.shp_grade_path, pixel_size)
                com.clip_shp_with_polygon_and_show(self.shp_grade_path, self.path_filepath)
            else:
                self.bin_file = self.ndvi_path.replace(".tif", ".BIN")
                self.shp_grade_path = self.ndvi_path.replace(".tif", "_grade.shp")
                # com.get_ndvi(self.ndvi_path, self.shp_grade_path,pixel_size)
                com.ndvi_grid_to_shp(self.ndvi_path, self.shp_grade_path, pixel_size)

                    # 显示分析开始的消息
            self.mes_show("Start analyse!", 5)
        except Exception as e:
            self.mes_show(f"Error: {str(e)}", 5)

    # 弹出错误消息框
    def show_error_message(self, message):
        msg = QMessageBox()
        msg.setIcon(QMessageBox.Critical)
        msg.setText(message)
        msg.setWindowTitle("Error")
        msg.exec_()

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = ':/plugins/FreeFertiCtrl/icon.png'
        self.add_action(
            icon_path,
            text=self.tr(u'FreeFretiCtrl'),
            callback=self.run,
            parent=self.iface.mainWindow())

    #--------------------------------------------------------------------------

    def onClosePlugin(self):
        """Cleanup necessary items here when plugin dockwidget is closed"""

        #print "** CLOSING FreeFertiCtrl"

        # disconnects
        self.dockwidget.closingPlugin.disconnect(self.onClosePlugin)

        # remove this statement if dockwidget is to remain
        # for reuse if plugin is reopened
        # Commented next statement since it causes QGIS crashe
        # when closing the docked window:
        # self.dockwidget = None

        self.pluginIsActive = False


    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""

        #print "** UNLOAD FreeFertiCtrl"

        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&FreeFertiCtrl'),
                action)
            self.iface.removeToolBarIcon(action)
        # remove the toolbar
        del self.toolbar

        # 重置所有的输入数据

    def reset_dockwidget(self):
        """清除上次输入的数据"""
        self.dockwidget.excellent_2.clear()
        self.dockwidget.good_2.clear()
        self.dockwidget.fair_2.clear()
        self.dockwidget.poor_2.clear()
        # self.dockwidget.Taskname.clear()
        self.dockwidget.Pixel_2.clear()
        self.dockwidget.Probar.setValue(0)
        self.dockwidget.Success.setText("")
        # 重置图层选择
        self.dockwidget.pathLayer_2.setLayer(None)
        self.dockwidget.NDVILayer_2.setLayer(None)
        self.dockwidget.gradeLayer_2.setLayer(None)
        # 在窗口或控件初始化时（例如在构造函数__init__中），加入以下代码来设置选择框初始状态为未选中
        self.dockwidget.IfSelect.setChecked(False)  # 设置为未选中状态
        self.dockwidget.pathLayer_2.setEnabled(False)

    def init_setting(self):
        # 将地块输入设置为shp图层
        self.dockwidget.pathLayer_2.setFilters(QgsMapLayerProxyModel.VectorLayer)
        # 将NDVI输入图层限制为栅格图层
        self.dockwidget.NDVILayer_2.setFilters(QgsMapLayerProxyModel.RasterLayer)
        # 将Grade输入图层限制为矢量图层
        self.dockwidget.gradeLayer_2.setFilters(QgsMapLayerProxyModel.VectorLayer)
        # "success提示"
        self.dockwidget.Success.setText("")
        # 对NDVI进行长势分析，当前首先进行的任务是，根据输入的N生成shp图层
        self.dockwidget.zhangshi.clicked.connect(self.get_shp)
        self.dockwidget.Probar.setValue(self.Probar_num)
        # self.dockwidget.XmlFile.fileChanged.connect(self.select_xml_file) #选择xml文件的存储位置
        self.dockwidget.Export.clicked.connect(self.save_to_iso_xml)  # export按钮导出功能
        self.dockwidget.IfSelect.stateChanged.connect(self.on_checkbox_state_changed)

    #--------------------------------------------------------------------------

    def run(self):
        """Run method that loads and starts the plugin"""

        if not self.pluginIsActive:
            self.pluginIsActive = True

            #print "** STARTING FreeFertiCtrl"

            # dockwidget may not exist if:
            #    first run of plugin
            #    removed on close (see self.onClosePlugin method)
            if self.dockwidget == None:
                # Create the dockwidget (after translation) and keep reference
                self.dockwidget = FreeFertiCtrlDockWidget()
                self.init_setting()

            # connect to provide cleanup on closing of dockwidget
            self.dockwidget.closingPlugin.connect(self.onClosePlugin)

            # show the dockwidget
            # TODO: fix to allow choice of dock location
            self.iface.addDockWidget(Qt.RightDockWidgetArea, self.dockwidget)
            self.dockwidget.show()
            self.reset_dockwidget()
